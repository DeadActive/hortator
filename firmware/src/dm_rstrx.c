#define RS_GAIN 153                                     /* the output gain, Q8: the defaults level with RIM's */

static int32_t rs_t2(const int16_t t[3][10], uint32_t i, uint32_t j, int32_t fp, int32_t fx)   /* bilinear, x 256 */
{
    int32_t a = t[i][j] * 256 + (int32_t)(((int64_t)(t[i][j + 1] - t[i][j]) * fx) >> 8);
    int32_t b = t[i + 1][j] * 256 + (int32_t)(((int64_t)(t[i + 1][j + 1] - t[i + 1][j]) * fx) >> 8);
    return a + (int32_t)(((int64_t)(b - a) * fp) >> 16);
}
static inline uint32_t rs_warp(const rstrx_t *r, uint32_t th)   /* the warped phase of th in [0, pi) (pi = 2^31) */
{
    return th < r->tj ? (uint32_t)(((uint64_t)th * r->kk) >> 16) : r->d0 + (uint32_t)(((uint64_t)(th - r->tj) * r->mm) >> 16);
}
static uint32_t rs_isqrt(uint64_t x)                   /* floor(sqrt(x)), bit by bit (trigger time only) */
{
    uint64_t q = 0, b = 1ull << 62;
    while (b > x)
        b >>= 2;
    while (b) {
        if (x >= q + b) {
            x -= q + b;
            q = (q >> 1) + b;
        } else
            q >>= 1;
        b >>= 2;
    }
    return (uint32_t)q;
}

/* RSTRX: TUNE DECAY DIST */
static void rstrx_trigger(track_t *t, dvoice_t *v)
{
    const int16_t *p = &t->p[P_E0];
    rstrx_t *r = &v->ms.rs;
    int32_t ds = clamp(p[2], 0, 127), p8, k, f;
    v->inc[0] = inc_tune(25165824u, dm_tune(t));        /* 172.27 Hz x (128 + 64) / 128 at TUNE 0 */
    p8 = clamp((int32_t)(v->inc[0] >> 9) - 32768, 0, 127 * 256);   /* the machine's PTCH, Q8 */
    k = p8 >= 120 * 256 ? 15 : p8 >> 11;
    f = k == 15 ? (p8 - 120 * 256) / 7 : (p8 & 2047) >> 3;
    r->amp = RS_AMP[k] + (((RS_AMP[k + 1] - RS_AMP[k]) * f) >> 8);
    r->e = 0x7FFFFFFFu;
    r->d_e = 0xFFFFFFFFu / ktrx_tau(591u, clamp(p[1], 0, 127) * 8088 / 1000, 1u);   /* DEC: tau 13.4 ms x
                                                         * e ^ (0.0292 v) */
    r->g = 0;
    if (ds) {                                           /* DIST: the warp at this pitch */
        uint32_t i = p8 < 64 * 256 ? 0u : 1u, j = 0, n;
        int32_t fp = i ? ((p8 - 64 * 256) << 8) / 63 : p8 << 2, fx, tj, dd, c = 0, s = 0;
        while (j < 8u && ds > RS_DX[j + 1])
            j++;
        fx = ((ds - RS_DX[j]) << 16) / (RS_DX[j + 1] - RS_DX[j]);
        tj = rs_t2(RS_TJ, i, j, fp, fx);
        dd = rs_t2(RS_DD, i, j, fp, fx);
        r->tj = (uint32_t)(((int64_t)tj * 119305) >> 8);   /* 0.01 degree x 256 -> phase (2^31 = 180 degrees) */
        r->d0 = r->tj - (uint32_t)(int32_t)(((int64_t)dd * 119305) >> 8);
        r->kk = (uint32_t)(((int64_t)rs_t2(RS_KK, i, j, fp, fx) * 6711) >> 18);   /* Q16 */
        r->mm = (0x80000000u - r->d0) / ((0x80000000u - r->tj) >> 16);           /* (pi - d0) / (pi - tj), Q16 */
        for (n = 0; n < 64u; n++) {                     /* the warped sine's fundamental (128 points, half a cycle) */
            uint32_t th = n << 25;
            int32_t y = sine_i(rs_warp(r, th));
            c += (y * sine_i(th + 0x40000000u)) >> 15;
            s += (y * sine_i(th)) >> 15;
        }
        n = rs_isqrt((uint64_t)((int64_t)c * c + (int64_t)s * s)) >> 5;   /* Q15 */
        r->g = (int32_t)(((int64_t)rs_t2(RS_FG, i, j, fp, fx) * 13421) >> 6) / (int32_t)(n ? n : 1u);   /* FG over
                                                         * it, Q14 (a 32-bit divide: FG x 2^29 / 10^4 < 2^30) */
    }
}

static void rstrx_render(track_t *t, dvoice_t *v, int32_t *out, uint32_t n)
{
    rstrx_t *r = &v->ms.rs;
    uint32_t i, tt = v->t;
    (void)t;
    for (i = 0; i < n; i++, tt++) {
        uint32_t ph = v->ph[0];
        int32_t s, y;
        if (r->g) {                                     /* DIST: the warped half-cycles */
            s = (sine_i(rs_warp(r, ph & 0x7FFFFFFFu)) * r->g) >> 14;
            if (ph >> 31)
                s = -s;
        } else
            s = sine_i(ph);
        v->ph[0] = ph + v->inc[0];
        y = mulq15(s, r->amp);
        if (tt < RS_NCLK)
            y += RS_CLICK[tt];
        y = mulq15(y, (int32_t)(r->e >> 16));
        y = (mulq15(mulq15(y, vel_gain(v)), VOICE_FS) * RS_GAIN) >> 8;
        out[i] += y;
        v->last = y;
        ktrx_fall(&r->e, r->d_e);
    }
    v->t = tt;
    if (r->e < (ENV_END << 7) && tt >= RS_NCLK)
        dm_end(v);
}

