"""START's decoder states for the built-in samples: felucca_samples.h -> felucca_seek.h.

The SAMPLE model's START (dm_sample.c) starts a sample at (n * START) >> 7, START 1..127. IMA ADPCM is a running
state (predictor, step index), so each start needs the state the decoder has there: for every sample (zones that
share one, same data offset and length, share a row) the 127 states, decoded from the header's own bytes with the
firmware's decoder (eng_sample.c sample_next). tests/slot_test.c checks every entry against the decoder in C.

    gen_seek.py build/gen/felucca_samples.h build/gen/felucca_seek.h
"""
import re
import sys
from pathlib import Path

IMA_STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88,
            97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658,
            724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660,
            4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818,
            18500, 20350, 22385, 24623, 27086, 29794, 32767]
IMA_IDX = [-1, -1, -1, -1, 2, 4, 6, 8]


def states(data, off, n):
    """[(pred, idx)] at (n * s) >> 7 for s = 1..127"""
    out, p, x, pos = [], 0, 0, 0
    for s in range(1, 128):
        target = (n * s) >> 7
        while pos < target:
            b = data[off + (pos >> 1)]
            c = b >> 4 if pos & 1 else b & 15
            st = IMA_STEP[x]
            vd = st >> 3
            if c & 4:
                vd += st
            if c & 2:
                vd += st >> 1
            if c & 1:
                vd += st >> 2
            p = max(-32768, min(32767, p - vd if c & 8 else p + vd))
            x = max(0, min(88, x + IMA_IDX[c & 7]))
            pos += 1
        out.append((p, x))
    return out


def main(src, dst):
    text = Path(src).read_text()
    m = re.search(r"SMP_DATA\[\d+\] = \{(.*?)\};", text, re.S)
    data = [int(v) for v in re.findall(r"\d+", m.group(1))]
    m = re.search(r"SMP_ZONES\[\] = \{(.*?)\n\};", text, re.S)
    zones = [[int(v) for v in re.findall(r"-?\d+", row)] for row in re.findall(r"\{([^{}]*)\}", m.group(1))]
    rows, row_of = [], []
    for z in zones:
        key = (z[0], z[1])                         # off, n
        if z[1] < 1:
            row_of.append(255)
            continue
        if key not in [r[0] for r in rows]:
            rows.append((key, states(data, z[0], z[1])))
        row_of.append([r[0] for r in rows].index(key))
    if len(rows) > 255:
        raise SystemExit("gen_seek: more than 255 samples")
    L = ["/* generated by tools/gen_seek.py from felucca_samples.h: START's ADPCM states (dm_sample.c) */",
         "#pragma once", f"#define SMP_SEEK_NROW {max(1, len(rows))}",
         f"static const uint8_t SMP_SEEK_ROW[{max(1, len(row_of))}] = {{" + ", ".join(map(str, row_of or [255])) + "};",
         f"static const int16_t SMP_SEEK_P[{max(1, len(rows))}][127] = {{"]
    for _, st in rows or [(None, [(0, 0)] * 127)]:
        L.append("    {" + ", ".join(str(p) for p, _ in st) + "},")
    L.append("};")
    L.append(f"static const uint8_t SMP_SEEK_I[{max(1, len(rows))}][127] = {{")
    for _, st in rows or [(None, [(0, 0)] * 127)]:
        L.append("    {" + ", ".join(str(x) for _, x in st) + "},")
    L.append("};")
    out = "\n".join(L) + "\n"
    if not Path(dst).exists() or Path(dst).read_text() != out:
        Path(dst).write_text(out)
    print(f"seek: {len(rows)} samples x 127 START states")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
