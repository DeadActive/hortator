"""firmware/src/preset_bank.h from tools/presets.json (the factory banks the owner approved: md-re
data/hortator_presets.json, copied; plan 2026-10-19-presets Task 5). Only MODEL, the 8 SOUND knobs and the name go into
the firmware; 'source' and 'note' stay here.

  tools/gen_presets.py            write firmware/src/preset_bank.h
  tools/gen_presets.py --check    exit 1 when the committed header differs from the JSON

A voice's first preset in the banks is its default sound: every DM_*_DEF's PD() defaults equal it (tests/preset_test.c
test_defaults_are_first_presets checks it, and the knob ranges).

Every factory preset has a "uid" (1..32767, unique): a project stores a track's factory preset by it (project.c, FDRD),
so a project saved on one firmware finds the same preset on a later one whose banks grew or were reordered. The rule:
uids are APPEND-ONLY. A preset keeps its uid for ever (moved to another place or bank, renamed, its knobs retouched);
a new preset takes a uid above every uid ever used; a removed preset's uid is never given again (an old project's
reference to it then reads as no preset). Only the order in the JSON (the banks, the id) may change freely."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools/presets.json"
OUT = ROOT / "firmware/src/preset_bank.h"
BANKS = ["MACHINEDRUM", "CLASSIC", "MODERN"]
TITLE = {"MACHINEDRUM": "MACHINEDRUM: the Machinedrum voices' factory-kit sounds (MATRX, CLTRX: none)",
         "CLASSIC": "CLASSIC 808 / 909", "MODERN": "MODERN / PLAITS (ACID, SMPL included)"}


def models():
    """the model names DMODELS lists (dmodels.c)"""
    t = (ROOT / "firmware/src/dmodels.c").read_text()
    m = re.search(r"DMODELS\[NMODELS\]\s*=\s*\{([^;]*)\};", t)
    return set(re.findall(r"DM_(\w+)_DEF", m.group(1)))


def header(banks):
    known = models()
    names, uids = set(), set()
    out = ["/* SPDX-License-Identifier: GPL-3.0-only",
           " * Drum machine fork: 2026 DEADACTIVE */",
           "/* GENERATED by tools/gen_presets.py from tools/presets.json: do not edit by hand.",
           " * The factory banks (presets.c): every preset {MODEL, the 8 SOUND knobs P_E0..P_E7, name <= 8 characters}, in",
           " * the banks' order (MACHINEDRUM, CLASSIC, MODERN); a preset's id is its index here (then the 128 user slots).",
           " * PRE_UID: each one's stable key (append-only, tools/gen_presets.py): what a project stores (project.c).",
           " * A voice's first preset is its default sound (drum_set_model; = its DM_*_DEF knobs). Included once, by presets.c */",
           "static const preset_t PRE_FACTORY[] = {"]
    if [b["bank"] for b in banks] != BANKS:
        raise SystemExit(f"gen_presets: banks must be {BANKS}")
    start, n, uid = [], 0, []
    for b in banks:
        start.append(n)
        out.append(f"    /* {TITLE[b['bank']]}: {len(b['presets'])} */")
        for p in b["presets"]:
            nm, mo, k = p["name"], p["model"], p["k"]
            if not re.fullmatch(r"[A-Z0-9 ]{1,8}", nm) or nm in names:
                raise SystemExit(f"gen_presets: bad or repeated name {nm!r}")
            if mo not in known:
                raise SystemExit(f"gen_presets: {nm}: no model {mo}")
            if len(k) != 8 or not all(isinstance(v, int) and -128 <= v <= 127 for v in k):
                raise SystemExit(f"gen_presets: {nm}: 8 knobs -128..127")
            u = p.get("uid")
            if not isinstance(u, int) or isinstance(u, bool) or not 1 <= u <= 0x7FFF or u in uids:
                raise SystemExit(f"gen_presets: {nm}: uid {u!r} missing, out of 1..32767 or repeated")
            names.add(nm)
            uids.add(u)
            uid.append(u)
            out.append(f"    {{DM_{mo}, {{{', '.join(str(v) for v in k)}}}, \"{nm}\"}},")
            n += 1
    out += ["};",
            "#define PRE_NFACT ((uint32_t)(sizeof PRE_FACTORY / sizeof PRE_FACTORY[0]))",
            f"typedef char pre_nfact_is[PRE_NFACT == {n}u ? 1 : -1];",
            "/* each factory preset's uid (the same order): a project's reference (append-only: never reused) */",
            "static const uint16_t PRE_UID[] = {"]
    for i in range(0, len(uid), 16):
        out.append("    " + ", ".join(str(u) for u in uid[i:i + 16]) + ",")
    out += ["};",
            "typedef char pre_uid_n[sizeof PRE_UID / sizeof PRE_UID[0] == PRE_NFACT ? 1 : -1];",
            "/* each bank's first id; PRE_BANK_START[PB_N]: the end of the user bank */",
            f"static const uint16_t PRE_BANK_START[PB_N + 1] = {{{start[0]}, {start[1]}, {start[2]}, PRE_NFACT, "
            "PRE_NFACT + PRE_NUSER};",
            ""]
    return "\n".join(out)


def main():
    text = header(json.loads(SRC.read_text()))
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != text:
            raise SystemExit("gen_presets: firmware/src/preset_bank.h differs from tools/presets.json "
                             "(run tools/gen_presets.py)")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
