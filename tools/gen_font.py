"""The Machinedrum-style pixel fonts (assets/fonts/md_font.txt) as C tables (run by tools/build.py):
  MD_F3   the MD's square 3x5 caps (drawn at 2x: 6x10), digits, signs
  MD_BIG  the MD's tempo digits, 5x8 with 2 px strokes
  MD_ICON 5x5 state glyphs (play, stop, record on / armed, USB)
md_font_t: per glyph a width (0: none) and h rows of bits (bit w-1-c = column c).
"""
import sys
from pathlib import Path

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"


def md_fonts(path):
    """assets/fonts/md_font.txt -> {font: {code: [row strings]}} (see the file's header for the format)"""
    fonts, cur = {}, None
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("# "):
            continue
        parts = line.split()
        if len(parts) == 2 and parts[0] in ("F3", "BIG", "ICON"):
            key = " " if parts[1] == "space" else parts[1]
            assert len(key) == 1, line
            cur = fonts.setdefault(parts[0], {}).setdefault(ord(key), [])
            continue
        assert cur is not None and set(line) <= {"#", "."}, line
        cur.append(line)
    return fonts


def md_lines(path):
    """the MD fonts as md_font_t tables: per glyph a width (0 = none) and h rows of bits (bit w-1-c = column c)"""
    lines = []
    for name, glyphs in md_fonts(path).items():
        h = len(next(iter(glyphs.values())))
        first, last = min(glyphs), max(glyphs)
        ws, rows = [], []
        for c in range(first, last + 1):
            g = glyphs.get(c)
            if g is None:
                ws.append(0)
                rows += [0] * h
                continue
            w = len(g[0])
            assert len(g) == h and all(len(r) == w for r in g) and 1 <= w <= 8, (name, chr(c))
            ws.append(w)
            rows += [int(r.replace("#", "1").replace(".", "0"), 2) for r in g]
        lines.append(f"static const uint8_t MD_{name}_W[{len(ws)}] = {{" + ", ".join(map(str, ws)) + "};")
        lines.append(f"static const uint8_t MD_{name}_ROWS[{len(rows)}] = {{")
        for i in range(0, len(rows), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in rows[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const md_font_t MD_{name} = {{ {h}, {first}, {last}, MD_{name}_W, MD_{name}_ROWS }};")
        lines.append("")
        print(f"font MD_{name}: h {h}, {first}..{last}, {sum(1 for w in ws if w)} glyphs, {len(ws) + len(rows)} B")
    return lines


def main(out):
    lines = ["/* generated by tools/gen_font.py from md_font.txt */", "#pragma once", "#include <stdint.h>", ""]
    lines += md_lines(FONTS / "md_font.txt")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
